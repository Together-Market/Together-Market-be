-- Spring Session JDBC infrastructure IDs are UUIDs, not domain/API IDs.
-- Additive migration: existing business tables and data are untouched.
CREATE TABLE app_sessions (
  PRIMARY_ID CHAR(36) NOT NULL,
  SESSION_ID CHAR(36) NOT NULL,
  CREATION_TIME BIGINT NOT NULL,
  LAST_ACCESS_TIME BIGINT NOT NULL,
  MAX_INACTIVE_INTERVAL INT NOT NULL,
  EXPIRY_TIME BIGINT NOT NULL,
  PRINCIPAL_NAME VARCHAR(100),
  PRIMARY KEY (PRIMARY_ID)
) ENGINE=InnoDB ROW_FORMAT=DYNAMIC;
CREATE UNIQUE INDEX app_sessions_ix1 ON app_sessions (SESSION_ID);
CREATE INDEX app_sessions_ix2 ON app_sessions (EXPIRY_TIME);
CREATE INDEX app_sessions_ix3 ON app_sessions (PRINCIPAL_NAME);
CREATE TABLE app_sessions_ATTRIBUTES (
  SESSION_PRIMARY_ID CHAR(36) NOT NULL,
  ATTRIBUTE_NAME VARCHAR(200) NOT NULL,
  ATTRIBUTE_BYTES BLOB NOT NULL,
  PRIMARY KEY (SESSION_PRIMARY_ID, ATTRIBUTE_NAME),
  CONSTRAINT app_sessions_attributes_fk FOREIGN KEY (SESSION_PRIMARY_ID)
    REFERENCES app_sessions(PRIMARY_ID) ON DELETE CASCADE
) ENGINE=InnoDB ROW_FORMAT=DYNAMIC;
