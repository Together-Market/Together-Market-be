), checked AS (
SELECT chosen.external_id, MAX(s.id) AS store_id,
CASE
 WHEN COUNT(p.id)=0 THEN 'MISSING_SOURCE'
 WHEN COUNT(p.id)>1 THEN 'DUPLICATE_SOURCE'
 WHEN MAX(p.matched_store_id) IS NULL THEN 'UNLINKED'
 WHEN COUNT(s.id)<>1 THEN 'INVALID_LINK'
 WHEN MAX(s.owner_id)<>1 THEN 'OWNER_MISMATCH'
 ELSE 'CONNECTED' END AS registration_status
FROM selected chosen
LEFT JOIN together_market.public_store_records p
 ON p.source='SBIZ' AND p.external_id=chosen.external_id
LEFT JOIN together_market.stores s ON s.id=p.matched_store_id
GROUP BY chosen.external_id
)
