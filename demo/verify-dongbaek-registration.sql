 COUNT(*) AS selected_count,
 COUNT(CASE WHEN registration_status='CONNECTED' THEN 1 END) AS connected_count,
 COUNT(DISTINCT CASE WHEN registration_status='CONNECTED' THEN store_id END) AS distinct_store_count,
 COUNT(CASE WHEN registration_status='UNLINKED' THEN 1 END) AS unlinked_count,
 COUNT(CASE WHEN registration_status NOT IN ('CONNECTED','UNLINKED') THEN 1 END) AS error_count
FROM checked;
